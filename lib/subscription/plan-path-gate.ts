/**
 * One map from a URL to the subscription feature that owns it.
 * Pages and APIs both use this. A path that is not listed is not plan-gated
 * (customers, items, payments, dashboard, and the plan settings screen).
 * The longest matching prefix wins, so /reports/gst is GST reports rather than basic reports.
 */

